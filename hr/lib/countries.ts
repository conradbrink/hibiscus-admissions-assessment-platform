/**
 * The list's own spelling for what the parent typed, or null when it is not
 * a country we know. Case and accents do not matter; a handful of common
 * alternatives (RSA, UK, Swaziland) are accepted.
 */
export function canonicalCountry(raw: string | null | undefined): string | null {
  const q = fold(raw ?? "");
  if (!q) return null;
  const alias = ALIASES[q];
  const target = alias && COUNTRY_NAMES.includes(alias) ? alias : null;
  if (target) return target;
  return COUNTRY_NAMES.find((n) => fold(n) === q) ?? null;
}

export function canonicalNationality(raw: string | null | undefined): string | null {
  const q = fold(raw ?? "");
  if (!q) return null;
  const alias = ALIASES[q];
  if (alias && NATIONALITIES.includes(alias)) return alias;
  const direct = NATIONALITIES.find((n) => fold(n) === q);
  if (direct) return direct;
  // A country name typed into the nationality box ("Botswana") is understood.
  const byCountry = canonicalCountry(raw);
  return byCountry ? (COUNTRIES.find((c) => c.name === byCountry)?.nationality ?? null) : null;
}
