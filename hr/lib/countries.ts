/** Every country, the school's own first, then A to Z. */
export const COUNTRIES: readonly Country[] = [
  ...PRIORITY_COUNTRIES.map((n) => ALL.find((c) => c.name === n)!),
  ...ALL.filter((c) => !(PRIORITY_COUNTRIES as readonly string[]).includes(c.name)),
];

export const COUNTRY_NAMES: readonly string[] = COUNTRIES.map((c) => c.name);
export const NATIONALITIES: readonly string[] = COUNTRIES.map((c) => c.nationality);

const fold = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[’']/g, "'").trim().toLowerCase();

/** A few spellings parents actually type, mapped to the list's entry. */
